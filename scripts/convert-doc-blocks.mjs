#!/usr/bin/env node

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocBlocks } from './lib/parseDocBlocks.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));

function printUsage() {
  console.error(`Usage: node scripts/convert-doc-blocks.mjs <export.txt> --slug SLUG --brand brainfood|soulfood [--format bitsize|bytesize] [--preview DIR]

Options:
  --slug SLUG       Post slug (used in output path)
  --brand BRAND     brainfood | soulfood
  --format FORMAT   bitsize | bytesize (overrides meta.format if set)
  --preview DIR     Write to src/app/design-preview/{DIR}/contentBlocks.ts instead of production path
`);
}

function parseArgs(argv) {
  const args = {
    input: null,
    slug: null,
    brand: null,
    format: null,
    preview: null,
  };

  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--slug') args.slug = argv[++i];
    else if (arg === '--brand') args.brand = argv[++i];
    else if (arg === '--format') args.format = argv[++i];
    else if (arg === '--preview') args.preview = argv[++i];
    else if (arg.startsWith('--')) {
      console.error(`Unknown option: ${arg}`);
      process.exit(1);
    } else {
      positional.push(arg);
    }
  }

  args.input = positional[0] ?? null;
  return args;
}

function serializeValue(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const padInner = '  '.repeat(indent + 1);

  if (value === null || value === undefined) return 'undefined';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    const items = value.map((item) => `${padInner}${serializeValue(item, indent + 1)}`).join(',\n');
    return `[\n${items},\n${pad}]`;
  }

  const entries = Object.entries(value).filter(([, v]) => v !== undefined);
  if (entries.length === 0) return '{}';
  const props = entries
    .map(([key, val]) => `${padInner}${key}: ${serializeValue(val, indent + 1)}`)
    .join(',\n');
  return `{\n${props},\n${pad}}`;
}

function generateOutput({ meta, blocks, sections }, brand, format) {
  const resolvedMeta = { ...meta, brand: brand ?? meta.brand, format: format ?? meta.format };
  const includeSectionNav = resolvedMeta.format === 'bytesize' && sections.length > 0;

  const lines = [
    '// Auto-generated by scripts/convert-doc-blocks.mjs — do not edit by hand',
    "import type { ContentBlock, PostMeta, SectionNavEntry } from '@/lib/contentBlocks/types';",
    '',
    `export const POST_META: PostMeta = ${serializeValue(resolvedMeta)} as const;`,
    '',
    `export const CONTENT_BLOCKS: ContentBlock[] = ${serializeValue(blocks)} as const;`,
  ];

  if (includeSectionNav) {
    lines.push('', `export const SECTION_NAV: SectionNavEntry[] = ${serializeValue(sections)} as const;`);
  }

  lines.push('');
  return lines.join('\n');
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  if (!args.input || !args.slug || !args.brand) {
    printUsage();
    process.exit(1);
  }

  const inputPath = resolve(args.input);
  const text = readFileSync(inputPath, 'utf8');

  let result;
  try {
    result = parseDocBlocks(text);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }

  const output = generateOutput(result, args.brand, args.format);

  const outputPath = args.preview
    ? resolve(__dirname, `../src/app/design-preview/${args.preview}/contentBlocks.ts`)
    : resolve(__dirname, `../src/app/${args.brand}/posts/${args.slug}/contentBlocks.ts`);

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output, 'utf8');

  console.log(`Wrote ${outputPath}`);
  if (result.sections.length > 0) {
    console.log(`Derived ${result.sections.length} section nav item(s).`);
  }
}

main();
